"""Write docs/monster-animations.md: per monster the ripped animation sets (frames, pictures, movement, boxes, sounds) and the validation against the public sheets.
usage: monster_anim_report.py ROM RIPDIR VALDIR OUT.md [ID[,ID...]]
RIPDIR/<id>/ is the output of tools/rip_monster_anims.py, VALDIR/<id>.json the output of tools/validate_monster_gfx.py (optional).
Only numbers are written."""
import sys, os, json, glob, re, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import romio, names

DIRS = ('up', 'right', 'down', 'left')


def load_set(d, name):
    p = os.path.join(d, name + '.json')
    return json.load(open(p)) if os.path.isfile(p) else None


def summary(j):
    pf = j['per_frame']
    n = j['total_frames']
    last = (pf['actor_dx'][-1], pf['actor_dy'][-1])
    peak = max(abs(v) for v in pf['jump_height']) if pf['jump_height'] else 0
    return dict(frames=n, pictures=len(j['frames']), move=last, jump=peak,
                weapon=sum(1 for b in pf['weapon_box'] if b[2] > 0 and b[3] > 0), proj=sum(1 for p in pf['projectile_pieces'] if p),
                sounds=sorted({s[1] for s in pf.get('sounds', [])}))


def section(rom, nm, rip, val, mid):
    d = os.path.join(rip, str(mid))
    idx = json.load(open(os.path.join(d, 'index.json')))
    out = ['## %02X %s' % (mid, nm), '']
    out.append('Ordinary table `%s` (%d animations), attack table `%s` (%d animations), body height %d. Ripped: %d animations over four facings.' % (
        idx['ordinary_table'], idx['ordinary_animations'], idx['attack_table'], idx['attack_animations'], idx['body_height'], len(idx['animations'])))
    v = val.get(mid)
    if v:
        t = v['total']
        out.append('Validation against the public sheet: %d pictures, %d exact, %d only under a recolouring (flash palettes), %d not found.' % (t['pictures'], t['exact'], t['recoloured_only'], t['not_found']))
    out.append('')
    out.append('| set | animation | frames (down) | pictures (4 facings) | displacement (right) | peak jump | weapon-box frames | projectile frames | sounds |')
    out.append('|---|---|---|---|---|---|---|---|---|')
    kinds = (('ord', 'ordinary, state 0 (one period of a loop)'), ('atk', 'attack table, pose command 0x40'), ('swing', 'attack table, swing state 0x80'),
             ('hurt', 'ordinary played as 0x80|n in state 0x40'), ('death', 'death effect'))
    missing = collections.defaultdict(list)
    for kind, _ in kinds:
        count = {'ord': idx['ordinary_animations'], 'atk': idx['attack_animations'], 'swing': idx['attack_animations'], 'hurt': idx['ordinary_animations'], 'death': 1}[kind]
        for a in range(count):
            nm_ = 'death' if kind == 'death' else '%s%02d' % (kind, a)
            per = {}
            for dn in DIRS:
                j = load_set(d, '%s_%s' % (nm_, dn))
                if j:
                    per[dn] = summary(j)
            if not per:
                missing[kind].append(a)
                continue
            s = per.get('down') or next(iter(per.values()))
            pics = sum(p['pictures'] for p in per.values())
            r = per.get('right', s)
            sounds = ' '.join('%02X' % x for x in s['sounds'])
            out.append('| %s | %s | %d | %d | %+d, %+d | %d | %d | %d | %s |' % (kind, nm_[len(kind):] or '-', s['frames'], pics, r['move'][0], r['move'][1], s['jump'], s['weapon'], s['proj'], sounds))
    for kind, ids in missing.items():
        out.append('')
        out.append('Not produced for `%s` (fewer than two frames, or no visible piece): %s.' % (kind, ' '.join('%02d' % a for a in ids)))
    out.append('')
    return out


def main():
    rom = romio.rom_from_argv()
    rip, valdir, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    ids = [int(x, 0) for x in sys.argv[4].split(',')] if len(sys.argv) > 4 else list(range(32))
    nm = names.load(rom)
    val = {}
    for mid in ids:
        p = os.path.join(valdir, '%d.json' % mid)
        if os.path.isfile(p):
            val[mid] = json.load(open(p))
    lines = ['# Ripped animations of the ordinary monsters 0x00-0x1F', '',
             'Generated by `tools/monster_anim_report.py` from the output of `tools/rip_monster_anims.py` (state `.zs3`-type arena, monster in slot 3, AI off, one picture per distinct frame, 60.0988 Hz) and `tools/validate_monster_gfx.py`.',
             'Set names: `ord NN` = ordinary animation NN in object state 0 (looping scripts are recorded for one period; a stand pose that never changes is recorded for 10 frames); `atk NN` = attack-table animation NN in state 0x40 (pose command); `swing NN` = attack-table animation NN in state 0x80 (swing command); `hurt NN` = ordinary animation NN played with id 0x80 | NN in state 0x40 (hit reactions use NN = 8 and 9; the other NN play the same scripts one-shot); `death` = the death effect until the object is gone. Every set is ripped for the four facings; the left facing is the mirror image of the right one.',
             'Columns: frames and pictures count distinct frames; displacement is the actor movement over the whole animation (pixels, right facing); peak jump is the largest jump height in pixels; weapon-box and projectile columns count frames; sounds are the sound ids requested.',
             'What the engine uses each animation for is in `docs/monster-animation-use.md` and `docs/monster-commands.md`; the AI scripts in `docs/monster-ai-opcodes.md`; which picture an animation shows when a command starts (the phase carries over between commands with the same animation id and facing) in `docs/monster-animation-phase.md`.', '']
    lines += ['## Summary', '', '| id | monster | animations ripped | pictures checked | exact | recoloured only | not found |', '|---|---|---|---|---|---|---|']
    for mid in ids:
        ip = os.path.join(rip, str(mid), 'index.json')
        if not os.path.isfile(ip):
            continue
        v = val.get(mid, {}).get('total', {})
        lines.append('| %02X | %s | %d | %s | %s | %s | %s |' % (mid, nm[0xCF + mid], len(json.load(open(ip))['animations']), v.get('pictures', '-'), v.get('exact', '-'), v.get('recoloured_only', '-'), v.get('not_found', '-')))
    lines += ['', 'Pictures that are not found are the projectile and effect pictures (arrows, stingers, spell effects, burst) and the poses the public sheets do not show; recoloured pictures are the flash palettes (hit flash, casting flash, petrified grey). Sheets: the monster sheets of the "Enemies" category plus "Status Ailments & Transformations" and "Death Effects".', '']
    for mid in ids:
        if not os.path.isfile(os.path.join(rip, str(mid), 'index.json')):
            continue
        lines += section(rom, nm[0xCF + mid], rip, val, mid)
    open(out_path, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
